# PowerShell script to extract dead functions from codeall.js into unneeded.js
# A function is "dead" if it's never called from any active file

$simsetDir = "C:\xampp\htdocs\beach\simset"
$codeallPath = Join-Path $simsetDir "codeall.js"
$unneededPath = Join-Path $simsetDir "unneeded.js"

# Read the entire file
$lines = Get-Content $codeallPath -Raw
$lineArray = Get-Content $codeallPath

Write-Host "Total lines in codeall.js: $($lineArray.Count)"

# Step 1: Find all top-level function definitions with their line ranges
$functions = @()
$currentFunc = $null
$braceCount = 0
$inFunction = $false

for ($i = 0; $i -lt $lineArray.Count; $i++) {
    $line = $lineArray[$i]
    $lineNum = $i + 1  # 1-indexed

    # Check for function definition at top level (not indented with spaces/tabs before 'function')
    if ($line -match '^\s*function\s+(\w+)\s*\(') {
        $funcName = $Matches[1]
        # This is a function definition
        if ($inFunction -and $currentFunc) {
            # Previous function ended (shouldn't happen at top level, but handle it)
            $currentFunc.EndLine = $i
            $functions += $currentFunc
        }
        $currentFunc = @{
            Name = $funcName
            StartLine = $i  # 0-indexed
            EndLine = $null
            BraceCount = 0
            Started = $false
        }
        $inFunction = $true
        $braceCount = 0
    }

    if ($inFunction) {
        # Count braces
        foreach ($char in $line.ToCharArray()) {
            if ($char -eq '{') { $braceCount++ }
            if ($char -eq '}') { $braceCount-- }
        }

        if ($braceCount -eq 0 -and $currentFunc.Started) {
            $currentFunc.EndLine = $i  # 0-indexed (inclusive)
            $functions += $currentFunc
            $currentFunc = $null
            $inFunction = $false
        }

        if ($braceCount -gt 0) { $currentFunc.Started = $true }
    }
}

# Handle any remaining function
if ($currentFunc) {
    $currentFunc.EndLine = $lineArray.Count - 1
    $functions += $currentFunc
}

Write-Host "Found $($functions.Count) function definitions"

# Step 2: Check which functions are dead (never called from active files)
$deadFunctions = @()
$aliveFunctions = @()

# Files to search (excluding code.js and temp_funcs.txt)
$activeFiles = @("codeall.js", "index.html", "start.js", "globals.js", "unittests.js")
for ($b = 0; $b -le 6; $b++) {
    $activeFiles += "bau$b.js"
}

foreach ($func in $functions) {
    $funcName = $func.Name
    $isDead = $true

    # Check each active file for references
    foreach ($file in $activeFiles) {
        $filePath = Join-Path $simsetDir $file
        if (Test-Path $filePath) {
            $content = Get-Content $filePath -Raw
            # Search for the function name as a word (not part of another word)
            # We use \b to match word boundaries, but also check for the function being used
            # in various contexts: called, assigned, passed as reference, etc.
            $pattern = "\b$([regex]::Escape($funcName))\b"
            $matches = [regex]::Matches($content, $pattern)

            if ($matches.Count -gt 0) {
                # If it's in codeall.js, check if there are references OTHER than the definition
                if ($file -eq "codeall.js") {
                    if ($matches.Count -gt 1) {
                        $isDead = $false
                        break
                    }
                } else {
                    $isDead = $false
                    break
                }
            }
        }
    }

    if ($isDead) {
        $deadFunctions += $func
    } else {
        $aliveFunctions += $func
    }
}

Write-Host "Dead functions: $($deadFunctions.Count)"
Write-Host "Alive functions: $($aliveFunctions.Count)"

# Step 3: Build unneeded.js content and new codeall.js content
$unneededLines = @()
$unneededLines += "// Functions moved from codeall.js - these are not called from any active code"
$unneededLines += "// Generated by extract_dead_code.ps1 on $(Get-Date -Format 'yyyy-MM-dd HH:mm:ss')"
$unneededLines += ""

$deadLineRanges = @()
foreach ($func in $deadFunctions) {
    # Collect the lines (0-indexed start to 0-indexed end inclusive)
    $deadLineRanges += @{
        Start = $func.StartLine
        End = $func.EndLine
        Name = $func.Name
    }
    # Add function to unneeded.js
    $funcLines = $lineArray[$func.StartLine..$func.EndLine]
    $unneededLines += $funcLines
    $unneededLines += ""
}

# Step 4: Build new codeall.js (only lines NOT in dead functions)
$deadLineSet = @{}
foreach ($range in $deadLineRanges) {
    for ($l = $range.Start; $l -le $range.End; $l++) {
        $deadLineSet[$l] = $true
    }
}

$newCodeAllLines = @()
for ($i = 0; $i -lt $lineArray.Count; $i++) {
    if (-not $deadLineSet.ContainsKey($i)) {
        $newCodeAllLines += $lineArray[$i]
    }
}

# Remove excessive blank lines (more than 2 consecutive)
$cleanedLines = @()
$blankCount = 0
foreach ($line in $newCodeAllLines) {
    if ($line.Trim() -eq "") {
        $blankCount++
        if ($blankCount -le 2) {
            $cleanedLines += $line
        }
    } else {
        $blankCount = 0
        $cleanedLines += $line
    }
}

Write-Host "Original codeall.js: $($lineArray.Count) lines"
Write-Host "New codeall.js: $($cleanedLines.Count) lines"
Write-Host "Lines removed: $($lineArray.Count - $cleanedLines.Count)"
Write-Host "unneeded.js: $($unneededLines.Count) lines"

# Step 5: Write the files
# Backup first
$backupPath = Join-Path $simsetDir "codeall.js.bak"
Copy-Item $codeallPath $backupPath -Force
Write-Host "Backup created: $backupPath"

# Write unneeded.js
$unneededContent = $unneededLines -join "`n"
[System.IO.File]::WriteAllText($unneededPath, $unneededContent, [System.Text.Encoding]::UTF8)
Write-Host "Written: $unneededPath"

# Write new codeall.js
$newCodeAllContent = $cleanedLines -join "`n"
[System.IO.File]::WriteAllText($codeallPath, $newCodeAllContent, [System.Text.Encoding]::UTF8)
Write-Host "Written: $codeallPath"

# Summary
Write-Host ""
Write-Host "=== SUMMARY ==="
Write-Host "Moved $($deadFunctions.Count) dead functions to unneeded.js"
Write-Host "codeall.js reduced from $($lineArray.Count) to $($cleanedLines.Count) lines"
Write-Host "Backup at: $backupPath"
